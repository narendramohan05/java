package forloop;
public class forloop {
    public static void main(String[] args) {
        System.out.println("even numbers");
        for (int i=0;i<=10;i+=2)
        {
            System.out.println(i);
        }
        System.out.println("odd numbers");
         for (int i=1;i<=10;i+=2)
        {
            System.out.println(i);
        }

    }
    
}
